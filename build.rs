//! Build script: embeds an optional VCS revision and turns `assets/kcore-logo.png`
//! into half-block cell art for the console header.

use std::path::Path;

/// Half-cell classes emitted into `logo_data.rs`.
const BG: u8 = 0;
const VIOLET: u8 = 1;
const WHITE: u8 = 2;

/// Logo variants as (name, columns, rows). One text row covers two pixel rows.
const VARIANTS: &[(&str, usize, usize)] =
    &[("LOGO_L", 56, 6), ("LOGO_M", 40, 4), ("LOGO_S", 32, 3)];

fn main() {
    emit_git_rev();
    emit_logo();
}

fn emit_git_rev() {
    println!("cargo:rerun-if-env-changed=KCORE_GIT_REV");
    if let Ok(rev) = std::env::var("KCORE_GIT_REV") {
        if !rev.trim().is_empty() {
            println!("cargo:rustc-env=KCORE_GIT_REV={rev}");
            return;
        }
    }
    if let Some(r) = std::process::Command::new("git")
        .args(["rev-parse", "--short", "HEAD"])
        .output()
        .ok()
        .filter(|o| o.status.success())
        .and_then(|o| String::from_utf8(o.stdout).ok())
        .map(|s| s.trim().to_string())
        .filter(|s| !s.is_empty())
    {
        println!("cargo:rustc-env=KCORE_GIT_REV={r}");
    }
}

struct Rgb {
    width: usize,
    height: usize,
    px: Vec<[u8; 3]>,
}

impl Rgb {
    fn at(&self, x: usize, y: usize) -> [u8; 3] {
        self.px[y * self.width + x]
    }
}

fn decode_png(path: &Path) -> Rgb {
    let file = std::fs::File::open(path).expect("open logo png");
    let mut decoder = png::Decoder::new(std::io::BufReader::new(file));
    decoder.set_transformations(png::Transformations::normalize_to_color8());
    let mut reader = decoder.read_info().expect("png header");
    let mut buf = vec![0u8; reader.output_buffer_size()];
    let info = reader.next_frame(&mut buf).expect("png frame");
    let channels = match info.color_type {
        png::ColorType::Rgb => 3,
        png::ColorType::Rgba => 4,
        png::ColorType::Grayscale => 1,
        png::ColorType::GrayscaleAlpha => 2,
        other => panic!("unsupported logo color type {other:?}"),
    };
    let width = info.width as usize;
    let height = info.height as usize;
    let mut px = Vec::with_capacity(width * height);
    for chunk in buf[..info.buffer_size()].chunks_exact(channels) {
        let rgb = match channels {
            1 | 2 => [chunk[0], chunk[0], chunk[0]],
            _ => [chunk[0], chunk[1], chunk[2]],
        };
        px.push(rgb);
    }
    Rgb { width, height, px }
}

fn is_ink(p: [u8; 3]) -> bool {
    u32::from(p[0]) + u32::from(p[1]) + u32::from(p[2]) > 150
}

/// Bounding box of the non-black content, as (x0, y0, x1, y1) with exclusive ends.
fn content_bbox(img: &Rgb) -> (usize, usize, usize, usize) {
    let (mut x0, mut y0, mut x1, mut y1) = (img.width, img.height, 0, 0);
    for y in 0..img.height {
        for x in 0..img.width {
            if is_ink(img.at(x, y)) {
                x0 = x0.min(x);
                y0 = y0.min(y);
                x1 = x1.max(x + 1);
                y1 = y1.max(y + 1);
            }
        }
    }
    if x1 <= x0 || y1 <= y0 {
        (0, 0, img.width, img.height)
    } else {
        (x0, y0, x1, y1)
    }
}

/// Box-filter the crop into `cols` x `rows` samples and classify each one.
fn classify_grid(
    img: &Rgb,
    bbox: (usize, usize, usize, usize),
    cols: usize,
    rows: usize,
) -> Vec<Vec<u8>> {
    let (x0, y0, x1, y1) = bbox;
    let cw = (x1 - x0) as f64 / cols as f64;
    let ch = (y1 - y0) as f64 / rows as f64;
    let mut grid = Vec::with_capacity(rows);
    for gy in 0..rows {
        let mut row = Vec::with_capacity(cols);
        let sy0 = y0 + (gy as f64 * ch) as usize;
        let sy1 = (y0 + ((gy + 1) as f64 * ch) as usize).max(sy0 + 1).min(y1);
        for gx in 0..cols {
            let sx0 = x0 + (gx as f64 * cw) as usize;
            let sx1 = (x0 + ((gx + 1) as f64 * cw) as usize).max(sx0 + 1).min(x1);
            let (mut r, mut g, mut b, mut n) = (0u64, 0u64, 0u64, 0u64);
            for y in sy0..sy1 {
                for x in sx0..sx1 {
                    let p = img.at(x, y);
                    r += u64::from(p[0]);
                    g += u64::from(p[1]);
                    b += u64::from(p[2]);
                    n += 1;
                }
            }
            let avg = [(r / n) as u8, (g / n) as u8, (b / n) as u8];
            let class = if !is_ink(avg) {
                BG
            } else if u32::from(avg[2]) > u32::from(avg[0]) + 60 {
                VIOLET
            } else {
                WHITE
            };
            row.push(class);
        }
        grid.push(row);
    }
    grid
}

fn emit_logo() {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir");
    let logo = Path::new(&manifest).join("assets/kcore-logo.png");
    println!("cargo:rerun-if-changed={}", logo.display());
    let img = decode_png(&logo);
    let bbox = content_bbox(&img);

    let mut out =
        String::from("// Generated by build.rs from assets/kcore-logo.png. Do not edit.\n");
    for (name, cols, rows) in VARIANTS {
        let grid = classify_grid(&img, bbox, *cols, rows * 2);
        out.push_str(&format!("pub static {name}: &[&[(u8, u8)]] = &[\n"));
        for row in grid.chunks(2) {
            out.push_str("    &[");
            for (top, bottom) in row[0].iter().zip(row[1].iter()) {
                out.push_str(&format!("({top},{bottom}),"));
            }
            out.push_str("],\n");
        }
        out.push_str("];\n");
    }

    let dest = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("logo_data.rs");
    std::fs::write(dest, out).expect("write logo_data.rs");
}
